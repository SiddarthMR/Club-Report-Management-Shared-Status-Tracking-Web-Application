export const INITIAL_REPORTS: ClubReport[] = BASE_REPORTS.map((r, index) => {
  const curriculum = getCurriculumForClassGroup(r.classGroup);
  
  // Exact user prompt example for Biosphere G6-G10 (Ms. Anusha R)
  let total = 25;
  let present = 22;
  let absent = 3;
  let absentNames = ['Rahul Kumar', 'Ananya S', 'Arjun P'];

  if (r.id === 'cie610-7' || (r.clubName === 'Biosphere' && r.teacherName === 'Ms. Anusha R')) {
    total = 25;
    present = 22;
    absent = 3;
    absentNames = ['Rahul Kumar', 'Ananya S', 'Arjun P'];
  } else {
    // Generate realistic attendance numbers
    total = 24 + (index % 7);
    const absentCount = index % 4; // 0, 1, 2, or 3
    absent = absentCount;
    present = total - absent;
    absentNames = absentCount === 0 ? [] : SAMPLE_ABSENT_NAMES[(index % SAMPLE_ABSENT_NAMES.length)].slice(0, absentCount);
  }

  const initialAttendance = {
    totalStudents: total,
    studentsPresent: present,
    studentsAbsent: absent,
    absentStudentNames: absentNames,
  };

  return {
    ...r,
    curriculum,
    totalStudents: total,
    studentsPresent: present,
    studentsAbsent: absent,
    absentStudents: absentNames,
    attendanceByDate: {
      '2026-10-05': initialAttendance,
      '2026-10-07': initialAttendance,
    },
  };
});

export function getInitialUsers(): TeacherUser[] {
  const admin: TeacherUser = {
    id: 'admin',
    name: 'Activity Coordinator / Admin',
    mobile: '9845012345',
    email: 'admin@pssemr.edu.in',
    role: 'admin',
    curriculums: ['CBSE', 'IGCSE / CIE'],
  };

  const teacherNames = Array.from(new Set(INITIAL_REPORTS.map((r) => r.teacherName)));

  const teachers: TeacherUser[] = teacherNames.map((name, i) => {
    const slug = name.toLowerCase().replace(/[^a-z0-9]/g, '');
    const mobileDigits = (9900000000 + i * 1111).toString().slice(0, 10);
    const teacherReports = INITIAL_REPORTS.filter((r) => r.teacherName === name);
    const curriculums = Array.from(new Set(teacherReports.map((r) => r.curriculum)));

    return {
      id: `teacher-${i + 1}`,
      name,
      mobile: mobileDigits,
      email: `${slug}@pssemr.edu.in`,
      role: 'teacher',
      curriculums,
    };
  });

  return [admin, ...teachers];
}
